const groups = entries.map(([ids, text]) => ({ beatIds: ids.split(" "), text }));

export function summariesFor(entry: ArchiveEntry): Summary[] {
  const position = new Map(entry.beatIds.map((id, index) => [id, index]));
  const result = groups
    .map(group => ({ text: group.text, beatIds: group.beatIds.filter(id => position.has(id)) }))
    .filter(group => group.beatIds.length > 0);
  const covered = new Set(result.flatMap(group => group.beatIds));
  const remaining = entry.beatIds.filter(id => !covered.has(id));
  if (remaining.length) result.push({ text: "本次会话还有其他已处理消息。", beatIds: remaining });
  return result.sort((a, b) => Math.min(...a.beatIds.map(id => position.get(id)!)) - Math.min(...b.beatIds.map(id => position.get(id)!)));
}
